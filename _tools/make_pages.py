def faq_ld(faq):
    strip = lambda s: html.unescape(re.sub("<[^>]+>", "", s))
    return {"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": [
        {"@type": "Question", "name": strip(q), "acceptedAnswer": {"@type": "Answer", "text": strip(a)}} for q, a in faq]}


